// /src/services/repositories/applications/supabase-applications-repository.ts

import { objectToCamelCase, objectToSnakeCase } from "@/lib/transform";
import { getCurrentUserId } from "@/services/supabase/auth";
import { supabase } from "@/services/supabase/client";
import type {
  Application,
  ApplicationCreateData,
  ApplicationUpdateData,
  ApplicationDb,
  ApplicationHistory,
  ApplicationHistoryDb,
} from "@/types";

import type { ApplicationsRepository } from "./applications-repository";
import type { RepositoryState } from "./types";

export function createSupabaseApplicationsRepository(): ApplicationsRepository {
  function fromDbApplication(row: ApplicationDb): Application {
    const { user_id: _userId, ...rest } = row;
    return objectToCamelCase(rest) as Application;
  }

  function toDbApplicationInsert(
    data: ApplicationCreateData,
  ): Partial<ApplicationDb> {
    // id, created_at, updated_at are generated by Supabase
    return objectToSnakeCase(data) as Partial<ApplicationDb>;
  }

  function toDbApplicationUpdate(
    data: ApplicationUpdateData,
  ): Partial<ApplicationDb> {
    // updated_at is maintained by the DB trigger
    const base = objectToSnakeCase(data) as Partial<ApplicationDb>;

    return Object.fromEntries(
      Object.entries(base).filter(([, v]) => v !== undefined),
    );
  }

  function fromDbHistory(row: ApplicationHistoryDb): ApplicationHistory {
    const { user_id: _userId, ...rest } = row;
    return objectToCamelCase(rest) as ApplicationHistory;
  }

  function toDbHistory(
    data: Partial<ApplicationHistory>,
  ): Partial<ApplicationHistoryDb> {
    // id and history_timestamp are generated by Supabase
    const { id: _id, historyTimestamp: _ts, ...rest } = data;
    return objectToSnakeCase(rest) as Partial<ApplicationHistoryDb>;
  }

  async function archive(
    app: Application,
    reason: "updated" | "deleted",
  ): Promise<void> {
    const userId = await getCurrentUserId();

    const { error } = await supabase!.from("application_history").insert({
      ...toDbHistory({ ...app, applicationId: app.id, reason }),
      user_id: userId,
    });

    if (error) throw error;
  }

  async function setState(state: RepositoryState): Promise<void> {
    const userId = await getCurrentUserId();

    // Delete existing data first — setState is a full replacement
    const { error: deleteHistoryError } = await supabase!
      .from("application_history")
      .delete()
      .eq("user_id", userId);
    if (deleteHistoryError) throw deleteHistoryError;

    const { error: deleteAppsError } = await supabase!
      .from("applications")
      .delete()
      .eq("user_id", userId);
    if (deleteAppsError) throw deleteAppsError;

    const idMap = new Map<string, string>();

    // -------------------------
    // APPLICATIONS
    // -------------------------
    const appsPayload = state.applications.map(app => {
      // Preserve UUID IDs (Supabase→Supabase round-trip); generate new ones
      // for slug-style IDs (local→Supabase migration)
      const isUuid =
        /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
          app.id,
        );
      const newId = isUuid ? app.id : crypto.randomUUID();
      idMap.set(app.id, newId);

      const { id: _id, ...rest } = app;

      return {
        ...objectToSnakeCase(rest),
        id: newId,
        user_id: userId,
      };
    });

    const { error: appError } = await supabase!
      .from("applications")
      .insert(appsPayload);

    if (appError) throw appError;

    // -------------------------
    // HISTORY
    // -------------------------
    if (state.history.length > 0) {
      const historyPayload = state.history.map(h => {
        const mappedAppId = idMap.get(h.applicationId);

        const { id: _id, applicationId: _applicationId, ...rest } = h;

        return {
          ...objectToSnakeCase(rest),
          id: crypto.randomUUID(),
          user_id: userId,

          // 🔥 IMPORTANT: allow deleted/orphaned applications
          application_id: mappedAppId ?? null,
        };
      });

      const { error: historyError } = await supabase!
        .from("application_history")
        .insert(historyPayload);

      if (historyError) throw historyError;
    }
  }

  async function getAll(): Promise<Application[]> {
    const { data, error } = await supabase!.from("applications").select("*");
    if (error) throw error;
    return (data ?? []).map(fromDbApplication);
  }

  async function getById(id: string): Promise<Application | null> {
    const { data, error } = await supabase!
      .from("applications")
      .select("*")
      .eq("id", id)
      .maybeSingle();
    if (error) throw error;
    return data ? fromDbApplication(data) : null;
  }

  async function getHistoryAll(): Promise<ApplicationHistory[]> {
    const { data, error } = await supabase!
      .from("application_history")
      .select("*");
    if (error) throw error;
    return (data ?? []).map(fromDbHistory);
  }

  async function getHistoryById(
    applicationId: string,
  ): Promise<ApplicationHistory[]> {
    const { data, error } = await supabase!
      .from("application_history")
      .select("*")
      .eq("application_id", applicationId);
    if (error) throw error;
    return (data ?? []).map(fromDbHistory);
  }

  async function create(data: ApplicationCreateData): Promise<Application> {
    const userId = await getCurrentUserId();

    const { data: created, error } = await supabase!
      .from("applications")
      .insert({ ...toDbApplicationInsert(data), user_id: userId })
      .select()
      .single();

    if (error) throw error;
    return fromDbApplication(created);
  }

  async function update(
    id: string,
    updates: ApplicationUpdateData,
  ): Promise<Application> {
    const existing = await getById(id);
    if (!existing) throw new Error("Not found");

    await archive(existing, "updated");

    const { data: updated, error } = await supabase!
      .from("applications")
      .update(toDbApplicationUpdate(updates))
      .eq("id", id)
      .select()
      .single();
    if (error) throw error;

    return fromDbApplication(updated);
  }

  async function remove(id: string): Promise<void> {
    const existing = await getById(id);
    if (!existing) throw new Error("Not found");

    await archive(existing, "deleted");

    const { error } = await supabase!
      .from("applications")
      .delete()
      .eq("id", id);

    if (error) throw error;
  }

  return {
    setState,
    getAll,
    getById,
    getHistoryAll,
    getHistoryById,
    create,
    update,
    remove,
  };
}
