// /src/services/repositories/job-sites/supabase-job-sites-repository.ts

import { generateCategoryId, generateSiteId } from "@/lib/generate-id";
import { objectToCamelCase, objectToSnakeCase } from "@/lib/transform";
import { getCurrentUserId } from "@/services/supabase/auth";
import { supabase } from "@/services/supabase/client";
import type {
  JobHuntData,
  JobCategory,
  JobCategoryCreateData,
  JobCategoryUpdateData,
  JobCategoryDb,
  JobSite,
  JobSiteCreateData,
  JobSiteUpdateData,
  JobSiteDb,
} from "@/types";

import type { JobSitesRepository } from "./job-sites-repository";

export function createSupabaseJobSitesRepository(): JobSitesRepository {
  function fromDbSite(row: JobSiteDb): JobSite {
    const { user_id: _userId, ...rest } = row;
    return objectToCamelCase(rest) as JobSite;
  }

  function toDbSiteInsert(
    data: JobSiteCreateData,
    userId: string,
  ): Partial<JobSiteDb> {
    // id is app-generated (slug-based); created_at/updated_at generated by DB
    return {
      ...(objectToSnakeCase(data) as Partial<JobSiteDb>),
      id: generateSiteId(data.name, data.url, data.atsType),
      user_id: userId,
    };
  }

  function toDbSiteUpdate(data: JobSiteUpdateData): Partial<JobSiteDb> {
    // updated_at maintained by DB trigger
    const base = objectToSnakeCase(data) as Partial<JobSiteDb>;
    return Object.fromEntries(
      Object.entries(base).filter(([, v]) => v !== undefined),
    );
  }

  function fromDbCategory(row: JobCategoryDb): JobCategory {
    const { user_id: _userId, ...rest } = row;
    return objectToCamelCase(rest) as JobCategory;
  }

  function toDbCategoryInsert(
    data: JobCategoryCreateData,
    userId: string,
    existingIds: Set<string>,
  ): Partial<JobCategoryDb> {
    // id is app-generated (slug-based); created_at/updated_at generated by DB
    return {
      ...(objectToSnakeCase(data) as Partial<JobCategoryDb>),
      id: generateCategoryId(data.name, existingIds),
      user_id: userId,
    };
  }

  function toDbCategoryUpdate(
    data: JobCategoryUpdateData,
  ): Partial<JobCategoryDb> {
    // updated_at maintained by DB trigger
    const base = objectToSnakeCase(data) as Partial<JobCategoryDb>;
    return Object.fromEntries(
      Object.entries(base).filter(([, v]) => v !== undefined),
    );
  }

  async function setState(data: JobHuntData): Promise<void> {
    if (!data) throw new Error("Invalid JobHuntData");

    const userId = await getCurrentUserId();

    // Delete sites first due to FK constraint on category_id
    const { error: deleteSitesError } = await supabase!
      .from("job_sites")
      .delete()
      .eq("user_id", userId);

    if (deleteSitesError) throw deleteSitesError;

    const { error: deleteCategoriesError } = await supabase!
      .from("job_categories")
      .delete()
      .eq("user_id", userId);

    if (deleteCategoriesError) throw deleteCategoriesError;

    if (data.categories?.length) {
      const categoriesPayload = data.categories.map(c => ({
        id: c.id,
        user_id: userId,
        name: c.name,
        description: c.description,
      }));

      const { error } = await supabase!
        .from("job_categories")
        .insert(categoriesPayload);

      if (error) throw error;
    }

    if (data.sites?.length) {
      const sitesPayload = data.sites.map(s => ({
        id: s.id,
        user_id: userId,
        name: s.name,
        url: s.url,
        category_id: s.categoryId,
        ats_type: s.atsType,
        notes: s.notes,
      }));

      const { error } = await supabase!.from("job_sites").insert(sitesPayload);

      if (error) throw error;
    }
  }

  async function getSites(): Promise<JobSite[]> {
    const { data, error } = await supabase!.from("job_sites").select("*");
    if (error) throw error;
    return (data ?? []).map(fromDbSite);
  }

  async function getSiteById(id: string): Promise<JobSite | null> {
    const { data, error } = await supabase!
      .from("job_sites")
      .select("*")
      .eq("id", id)
      .maybeSingle();
    if (error) throw error;
    return data ? fromDbSite(data) : null;
  }

  async function createSite(data: JobSiteCreateData): Promise<JobSite> {
    const userId = await getCurrentUserId();

    const { data: created, error } = await supabase!
      .from("job_sites")
      .insert(toDbSiteInsert(data, userId))
      .select()
      .single();
    if (error) throw error;

    return fromDbSite(created);
  }

  async function updateSite(
    id: string,
    updates: JobSiteUpdateData,
  ): Promise<JobSite> {
    const { data: updated, error } = await supabase!
      .from("job_sites")
      .update(toDbSiteUpdate(updates))
      .eq("id", id)
      .select()
      .single();
    if (error) throw error;

    return fromDbSite(updated);
  }

  async function removeSite(id: string): Promise<void> {
    const { error } = await supabase!.from("job_sites").delete().eq("id", id);
    if (error) throw error;
  }

  async function getCategories(): Promise<JobCategory[]> {
    const { data, error } = await supabase!.from("job_categories").select("*");
    if (error) throw error;
    return (data ?? []).map(fromDbCategory);
  }

  async function getCategoryById(id: string): Promise<JobCategory | null> {
    const { data, error } = await supabase!
      .from("job_categories")
      .select("*")
      .eq("id", id)
      .maybeSingle();
    if (error) throw error;
    return data ? fromDbCategory(data) : null;
  }

  async function createCategory(
    data: JobCategoryCreateData,
  ): Promise<JobCategory> {
    const userId = await getCurrentUserId();
    const existing = await getCategories();
    const existingIds = new Set(existing.map(c => c.id));

    const { data: created, error } = await supabase!
      .from("job_categories")
      .insert(toDbCategoryInsert(data, userId, existingIds))
      .select()
      .single();
    if (error) throw error;

    return fromDbCategory(created);
  }

  async function updateCategory(
    id: string,
    updates: JobCategoryUpdateData,
  ): Promise<JobCategory> {
    const { data: updated, error } = await supabase!
      .from("job_categories")
      .update(toDbCategoryUpdate(updates))
      .eq("id", id)
      .select()
      .single();
    if (error) throw error;

    return fromDbCategory(updated);
  }

  async function removeCategory(id: string): Promise<void> {
    const { error } = await supabase!
      .from("job_categories")
      .delete()
      .eq("id", id);
    if (error) throw error;
  }

  return {
    setState,
    getSites,
    getSiteById,
    createSite,
    updateSite,
    removeSite,
    getCategories,
    getCategoryById,
    createCategory,
    updateCategory,
    removeCategory,
  };
}
